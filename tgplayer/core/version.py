# -*- coding: utf-8 -*-
"""Версия плеера — в одном месте, чтобы нигде не разъезжалась.

Формат: MAJOR.MINOR.PATCH<буква схемы загрузчика>

    2.4.0c
    │ │ │ └─ схема загрузки: a, b, c, ... — какая именно логика качает куски
    │ │ └─── исправления поведения (багфиксы)
    │ └───── новые возможности, видимые в интерфейсе
    └────── смена архитектуры

Почему буква в конце. Дата сборки различала сборки, но ничего не говорила о
самом важном: именно схема загрузки ломалась чаще всего, и по дате нельзя
было понять, что внутри. Буква это и показывает.

Схемы загрузчика по порядку:

    a — исходная (сборка 18.10): поднимается только хвост, таймаут 12 с
    b — поднимаются хвост И начало одновременно
    c — четыре воркера, таймаут снижен до 6 с
    d — возврат к схеме «a» после отката (текущая)

Меняя поведение загрузчика (число воркеров, приоритеты, таймауты, порядок
подъёма участков файла) — ОБЯЗАТЕЛЬНО меняйте букву. Иначе по версии
снова станет непонятно, что внутри.
"""

MAJOR = 2
MINOR = 9
PATCH = 0
LOADER = 'd'

VERSION = f"{MAJOR}.{MINOR}.{PATCH}{LOADER}"

# Дата выпуска этой версии. Год «производства» показывается в настройках.
RELEASE_DATE = '27 октября 2026'
RELEASE_YEAR = 2026

# Название программы. Одно место — чтобы не разъезжалось по файлам.
APP_NAME = 'TGPlayer'

# Расшифровка для журнала и окна «О программе».
LOADER_TITLES = {
    'a': 'исходная (18.10): только хвост, таймаут 12 с',
    'b': 'хвост и начало одновременно',
    'c': 'четыре воркера, таймаут 6 с',
    'd': 'возврат к исходной схеме после отката',
}


def version_text():
    """Короткая строка версии: «2.5.0d»."""
    return VERSION


def full_version_text():
    """Строка для журнала: версия и расшифровка схемы загрузчика."""
    loader = LOADER_TITLES.get(LOADER, 'неизвестная')
    return f"{VERSION} (загрузчик {LOADER}: {loader})"


def window_title(base=None):
    """Заголовок окна с версией."""
    return f"{base or APP_NAME} {VERSION}"


def about_text():
    """Текст блока «О программе» для настроек.

    Собирается из отдельных строк, чтобы в окне настроек он выглядел как
    обычный блок сведений, а не как одна длинная строка.
    """
    return (
        f"{APP_NAME} {VERSION}",
        f"Выпуск: {RELEASE_DATE} (сборка {RELEASE_YEAR} года)",
        f"Схема загрузки: {LOADER} — {LOADER_TITLES.get(LOADER, 'неизвестная')}",
        "Сделано с помощью ИИ (DeepSeek).",
        "Telegram-клиент: Telethon. Видео: libmpv.",
    )
