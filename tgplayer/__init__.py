"""Плеер видео из Telegram — пакет модулей.

Раньше всё лежало в одном файле на 11 тысяч строк, и найти в нём нужное
место можно было только поиском. Теперь код разложен по слоям: каждый
слой знает только те, что ниже него.

::

    core/        основы, ничего не знают о программе
      paths        каталоги данных и ресурсов
      log          журнал tgplayer.log и перехват print
      config       числовые настройки, пороги, тексты
      theme        палитры, цвета, таблица стилей
      settings     settings.json и геометрия окон
      history      история просмотров
      utils        мелочи: время, скорость, сеть
      proxy        поиск и выбор прокси

    system/      окружение, без окон
      mpv_boot     загрузка libmpv и диагностика
      telethon_boot ленивая загрузка Telethon

    icons/       рисование значков
    widgets/     виджеты: ползунки, панель управления, PiP
    backend/     Telegram: клиент, кеш, HTTP-сервер
    player/      окно плеера
    windows/     главное окно, диалоги
    app.py       точка входа

Точка входа прежняя — ``player_deepseek.py``. Он остаётся фасадом:
импортирует всё и реэкспортирует под старыми именами, поэтому тесты и
сборка, которые обращаются к ``player_deepseek.PlayerWindow`` и
остальному, продолжают работать без правок.
"""

